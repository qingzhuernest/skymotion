"""Bake Charter italic outlines into the font-independent constellation.
Maintenance only: requires fontTools and brotli; no runtime font download.
"""
import json, math
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.basePen import BasePen
root = (Path(__file__).resolve().parents[1] / "site")
font = TTFont(root / 'fonts/charter_italic.woff2')
glyphs = font.getGlyphSet()
class OutlinePen(BasePen):
    def __init__(self):
        super().__init__(glyphs)
        self.paths = []
        self.path = []
    def _moveTo(self, p): self.path = [p]
    def _lineTo(self, p): self.path.append(p)
    def _curveToOne(self, a, b, c):
        p = self.path[-1]
        for i in range(1, 17):
            t = i / 16; u = 1-t
            self.path.append(tuple(u**3*p[k]+3*u*u*t*a[k]+3*u*t*t*b[k]+t**3*c[k] for k in (0,1)))
    def _qCurveToOne(self, a, b):
        p = self.path[-1]
        for i in range(1, 17):
            t = i / 16; u = 1-t
            self.path.append(tuple(u*u*p[k]+2*u*t*a[k]+t*t*b[k] for k in (0,1)))
    def _closePath(self):
        if self.path[-1] != self.path[0]: self.path.append(self.path[0])
        self.paths.append(self.path)
    def _endPath(self): self.paths.append(self.path)
paths = []; advance = 0
for char in 'Ad Astra':
    name = font.getBestCmap()[ord(char)]
    pen = OutlinePen(); glyphs[name].draw(pen)
    paths.extend([[(x+advance, y) for x,y in path] for path in pen.paths])
    advance += font['hmtx'].metrics[name][0] + (18 if char != ' ' else 70)
xs = [x for path in paths for x,y in path]; ys = [y for path in paths for x,y in path]
scale = 460/(max(xs)-min(xs)); height = (max(ys)-min(ys))*scale
paths = [[((x-min(xs))*scale, (max(ys)-y)*scale+(100-height)/2) for x,y in path] for path in paths]
# Keep curve error below half a design unit and discard redundant curve samples.
# This bounds star count on mobile while preserving the source typeface's proportions.
def simplify(points, tolerance=0.45):
    if len(points) <= 2: return points
    a,b = points[0],points[-1]; dx,dy = b[0]-a[0],b[1]-a[1]
    length = math.hypot(dx,dy)
    distances = [abs(dx*(a[1]-y)-(a[0]-x)*dy)/length if length else math.hypot(x-a[0],y-a[1]) for x,y in points[1:-1]]
    maximum = max(distances,default=0)
    if maximum <= tolerance: return [a,b]
    index = distances.index(maximum)+1
    return simplify(points[:index+1],tolerance)[:-1]+simplify(points[index:],tolerance)
paths = [simplify(path) for path in paths]
# Star density is chosen separately by the runtime.
source = root / 'welcome.js'; text = source.read_text()
start = text.index('  const letterPaths = ['); end = text.index('  const openingNodes', start)
comment = '  // Charter italic outlines, generated by scripts/generate-welcome-lettering.py.\n'
while text[:start].endswith(comment): start -= len(comment)
encoded = '\n'.join('    '+json.dumps([[round(x,2),round(y,2)] for x,y in path],separators=(',',':'))+',' for path in paths)
text = text[:start]+'  // Charter italic outlines, generated by scripts/generate-welcome-lettering.py.\n  const letterPaths = [\n'+encoded+'\n  ];\n'+text[end:]
source.write_text(text)
print(f'Baked {len(paths)} contours; optical height {height:.1f} in a 460-unit wordmark.')
